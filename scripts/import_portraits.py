#!/usr/bin/env python3
"""Audit user-provided, locally licensed character renders and update manifest.

This only validates basic image suitability (portrait layout + real transparency).
YOU must visually confirm each file shows the correctly named character from
head to feet; no automatic algorithm can verify identity or full-body coverage.
"""
from pathlib import Path
from PIL import Image
import sys

ROOT=Path(__file__).resolve().parents[1]
PATH=ROOT/'assets/portraits'
MANIFEST=ROOT/'src/portrait_media_manifest.mjs'
KNOWN=['alter','ash','axle','ballistic','bangalore','bloodhound','catalyst','caustic','conduit','crypto','fuse','gibraltar','horizon','lifeline','loba','mad-maggie','mirage','newcastle','octane','pathfinder','rampart','revenant','seer','sparrow','valkyrie','vantage','wattson','wraith']
MISSING=['vantage','sparrow','rampart','revenant','loba','gibraltar','conduit','catalyst','ballistic','alter']
accepted={}
for slug in KNOWN:
 for ext in ['webp','png']:
  file=PATH/f'{slug}.{ext}'
  if not file.is_file():continue
  with Image.open(file) as img:
   rgba=img.convert('RGBA');w,h=img.size
   trans=rgba.getchannel('A').getextrema()[0]<210
   if not (w>=350 and h>=500 and h>=w*1.25 and trans):
    print(f'SKIP {file.name}: expected portrait >=350×500, height >=1.25×width and actual alpha transparency (got {w}×{h}, transparency={trans})')
    continue
   accepted[slug]=file.name
   print(f'OK   {file.name}: {w}×{h} with alpha; VERIFY IDENTITY + HEAD-TO-BOOTS VISUALLY')
  break
if '--apply' in sys.argv:
 lines=['/** Visually confirmed transparent full-body character renders only.',' * Generated by scripts/import_portraits.py. Identity and body coverage require manual inspection. */','export const localPortraitFiles=Object.freeze({']
 lines.extend(f"  '{slug}':'{file}'," for slug,file in sorted(accepted.items()))
 lines.extend(['});',f"export const desiredFullBodySlugs=Object.freeze({MISSING!r});",''])
 MANIFEST.write_text('\n'.join(lines))
 print('Manifest updated:',MANIFEST)
else:
 print('Dry run only. Add --apply after manually verifying every detected character render.')
print('Still missing requested portraits:',', '.join(s for s in MISSING if s not in accepted) or 'none')
